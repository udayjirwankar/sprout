def read_json_object():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        raise ValueError('Send a JSON object.')
    return data


def read_chip_list(data, field):
    values = data.get(field, [])
    if not isinstance(values, list) or len(values) > 16:
        raise ValueError(f'{field} must be a list of up to 16 selections.')
    if any(not isinstance(value, str) or not value.strip() or len(value) > 100 for value in values):
        raise ValueError(f'{field} contains an invalid selection.')
    return list(dict.fromkeys(value.strip() for value in values))


def decode_chip_list(value):
    try:
        values = json.loads(value) if value else []
        return [item for item in values if isinstance(item, str)] if isinstance(values, list) else []
    except (json.JSONDecodeError, TypeError):
        return []


def utc_timestamp(value):
    # SQLite CURRENT_TIMESTAMP is UTC; make the timezone explicit in the API.
    return value.replace(' ', 'T') + 'Z' if value else None


