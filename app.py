def get_db_connection():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute('PRAGMA foreign_keys = ON')
    return conn


def remove_legacy_samples():
    """Remove only the exact demonstration records previously generated by Sprout."""
    conn = get_db_connection()
    try:
        with conn:
            conn.execute(
                "DELETE FROM escalation_alerts WHERE student_id LIKE 'GUEST-%' AND signal_summary = ?",
                ('Sample alert for demonstrating the counselor review workflow.',)
            )
            entries = conn.execute(
                "SELECT entry_id, encrypted_content FROM journal_entries WHERE student_id LIKE 'GUEST-%'"
            ).fetchall()
            for entry in entries:
                try:
                    content = decrypt_text(entry['encrypted_content'])
                except (InvalidToken, ValueError, UnicodeDecodeError):
                    continue
                if content == 'Sample reflection: I made time to check in with myself today.':
                    conn.execute('DELETE FROM journal_entries WHERE entry_id = ?', (entry['entry_id'],))
    finally:
        conn.close()


remove_legacy_samples()


def csrf_token():
    if 'csrf_token' not in session:
        session['csrf_token'] = secrets.token_urlsafe(32)
    return session['csrf_token']


@app.context_processor
def template_helpers():
    return {'csrf_token': csrf_token, 'demo_student_id': g.student_id}


def create_demo_workspace():
    student_id = 'GUEST-' + uuid.uuid4().hex
    conn = get_db_connection()
    try:
        with conn:
            stale = "SELECT student_id FROM students WHERE student_id LIKE 'GUEST-%' AND created_at < datetime('now', '-1 day')"
            for table in ['journal_entries', 'escalation_alerts', 'daily_stats']:
                conn.execute(f'DELETE FROM {table} WHERE student_id IN ({stale})')
            conn.execute(f'DELETE FROM students WHERE student_id IN ({stale})')
            conn.execute('INSERT INTO students (student_id, name) VALUES (?, ?)', (student_id, 'Guest'))
    finally:
        conn.close()
    session.clear()
    session['demo_student_id'] = student_id
    session.permanent = True
    return student_id


@app.before_request
def prepare_demo_workspace():
    g.student_id = None
    if request.endpoint not in {
        'student_home', 'counselor_dashboard', 'save_journal', 'get_student_history',
        'get_counselor_alerts', 'update_alert_status', 'reset_demo',
    }:
        return

    # A signed browser cookie identifies the demo workspace. There are no accounts.
    student_id = session.get('demo_student_id') or session.get('guest_student_id')
    conn = get_db_connection()
    try:
        student = conn.execute(
            "SELECT student_id FROM students WHERE student_id = ? "
            "AND student_id LIKE 'GUEST-%' AND created_at >= datetime('now', '-1 day')",
            (student_id,)
        ).fetchone() if student_id else None
    finally:
        conn.close()
    if student:
        g.student_id = student['student_id']
        session['demo_student_id'] = g.student_id
        for old_key in ['guest_student_id', 'guest_role', 'user_id']:
            session.pop(old_key, None)
    elif request.endpoint in {'student_home', 'counselor_dashboard'} and request.method in {'GET', 'HEAD'}:
        g.student_id = create_demo_workspace()
    else:
        return jsonify(error='Your demo workspace expired. Copy any draft, then refresh Sprout.'), 409

    if request.method in {'POST', 'PATCH', 'PUT', 'DELETE'}:
        supplied = request.headers.get('X-CSRF-Token') or request.form.get('csrf_token', '')
        expected = session.get('csrf_token', '')
        if not expected or not hmac.compare_digest(expected.encode(), supplied.encode()):
            return jsonify(error='Refresh the page and try again.'), 400


