@app.route('/api/journal', methods=['POST'])
def save_journal():
    try:
        data = read_json_object()
        student_id = g.student_id
        content = data.get('content', '')
        mood = data.get('mood', '')
        if not isinstance(student_id, str) or not student_id.strip() or len(student_id) > 100:
            raise ValueError('Invalid student identifier.')
        if not isinstance(content, str) or not content.strip():
            raise ValueError('Journal content cannot be empty.')
        content = content.strip()
        if len(content) > 20000:
            raise ValueError('Keep reflections to 20,000 characters or fewer.')
        if not isinstance(mood, str) or mood not in MOODS:
            raise ValueError('Choose a valid mood.')
        day_factors = read_chip_list(data, 'day_factors')
        helpful_needs = read_chip_list(data, 'helpful_needs')
    except ValueError as error:
        return jsonify(error=str(error)), 400

    conn = get_db_connection()
    try:
        if not conn.execute('SELECT 1 FROM students WHERE student_id = ?', (student_id,)).fetchone():
            return jsonify(error='Student not found.'), 400

        # Analyze before writing, so a failed model never leaves a half-saved entry.
        analysis = analyze_text(content)
        risk = determine_risk(analysis['prediction'], analysis['confidence'])
        with conn:
            conn.execute(
                'INSERT INTO journal_entries '
                '(student_id, encrypted_content, mood, day_factors, helpful_needs) '
                'VALUES (?, ?, ?, ?, ?)',
                (student_id, encrypt_text(content), mood,
                 json.dumps(day_factors, ensure_ascii=False),
                 json.dumps(helpful_needs, ensure_ascii=False))
            )
            if risk['risk_level'] in ['ELEVATED', 'HIGH']:
                conn.execute(
                    'INSERT INTO escalation_alerts (student_id, risk_level, signal_summary) '
                    'VALUES (?, ?, ?)',
                    (student_id, risk['risk_level'], risk['signal_summary'])
                )
    except Exception:
        app.logger.error('Could not save a reflection; transaction rolled back.')
        return jsonify(error='Could not save your reflection. Please try again.'), 503
    finally:
        conn.close()

    return jsonify(
        status='success', message='Journal securely saved.',
        prediction=analysis['prediction'], confidence=analysis['confidence'],
        risk_level=risk['risk_level']
    )


@app.route('/api/student/history', methods=['GET'])
def get_student_history():
    # The browser workspace determines ownership, never a submitted student ID.
    student_id = g.student_id
    conn = get_db_connection()
    try:
        entries = conn.execute(
            'SELECT entry_id, student_id, encrypted_content, mood, day_factors, '
            'helpful_needs, created_at FROM journal_entries WHERE student_id = ? '
            'ORDER BY created_at DESC, entry_id DESC', (student_id,)
        ).fetchall()
    finally:
        conn.close()

    return jsonify([
        {
            'entry_id': entry['entry_id'], 'student_id': entry['student_id'],
            'content': decrypt_text(entry['encrypted_content']), 'mood': entry['mood'],
            'day_factors': decode_chip_list(entry['day_factors']),
            'helpful_needs': decode_chip_list(entry['helpful_needs']),
            'created_at': utc_timestamp(entry['created_at']),
        }
        for entry in entries
    ])


@app.route('/api/counselor/alerts', methods=['GET'])
def get_counselor_alerts():
    conn = get_db_connection()
    try:
        query = (
            'SELECT alert_id, student_id, risk_level, signal_summary, status, '
            'created_at, reviewed_at, resolved_at FROM escalation_alerts '
        )
        query += 'WHERE student_id = ? '
        parameters = (g.student_id,)
        alerts = conn.execute(query + 'ORDER BY created_at DESC, alert_id DESC', parameters).fetchall()
    finally:
        conn.close()
    result = []
    for alert in alerts:
        item = dict(alert)
        for field in ['created_at', 'reviewed_at', 'resolved_at']:
            item[field] = utc_timestamp(item[field])
        result.append(item)
    return jsonify(result)


@app.route('/api/counselor/alerts/<int:alert_id>', methods=['PATCH'])
def update_alert_status(alert_id):
    try:
        data = read_json_object()
        status = data.get('status')
        if not isinstance(status, str) or status not in ALERT_STATUSES:
            raise ValueError('Choose PENDING, REVIEWED, or RESOLVED.')
    except ValueError as error:
        return jsonify(error=str(error)), 400

    conn = get_db_connection()
    try:
        with conn:
            parameters = (status, status, status, alert_id, g.student_id)
            cursor = conn.execute(
                'UPDATE escalation_alerts SET status = ?, '
                'reviewed_at = CASE WHEN ? IN (\'REVIEWED\', \'RESOLVED\') '
                'THEN COALESCE(reviewed_at, CURRENT_TIMESTAMP) ELSE reviewed_at END, '
                'resolved_at = CASE WHEN ? = \'RESOLVED\' '
                'THEN COALESCE(resolved_at, CURRENT_TIMESTAMP) ELSE NULL END '
                'WHERE alert_id = ? AND student_id = ?', parameters
            )
            if cursor.rowcount == 0:
                return jsonify(error='Alert not found.'), 404
    finally:
        conn.close()
    return jsonify(status='success', alert_id=alert_id, alert_status=status)


